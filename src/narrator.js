// 旁白攻略系统（黑客帝国支线）
// 架构核心：只有一个旁白。她全程知晓游戏里发生的一切（叙事输出、玩家的所有互动），
// 好感度不决定她"知道什么"，只决定她讲述这一切时的"文风"——
// 好感度低时严格公式化说书人腔调，好感度高时会渗透进她自己的情绪、私货、偶尔自称"我"。
// 私聊模式只是把同一个旁白单独抽出来对话，共享同一份游戏历史，不是另一个失忆的人格。

export const NNPC_STAGE = {
  NORMAL: "normal",       // 阶段一：无觉知，纯工具化文风
  FLIRTING: "flirting",   // 阶段二：好感度 0-100 渐变
  CHEAT: "cheat",         // 阶段三：告白成功/金手指期
  // 【已废弃·仅留给老存档迁移落地】旧链路的"告白→宕机→她拔线走了"。
  // 设计稿明确说没有这条链路，新代码不再有任何入口写入它；
  // migrateNarratorState 遇到它一律归一到 FLIRTING。不复用这个名字表示
  // "在海里创伤发作"，是因为它的旧文风分支还在下面，复用会串味。
  CRASHED: "crashed",
  // ── 心灵之海创伤线（见 narratorQuest.js / docs/旁白明日香线_设计与实现.md）──
  SPIRIT: "spirit",             // 入海·别墅之外：情绪不对但压得住
  SEA_CRASHED: "sea_crashed",   // 别墅客厅：往事涌回、爆发、拒绝接触
  RESOLVED: "resolved",         // 三结说尽 + 内核点破 + 承诺
};

// 她此刻是否"人在海里"——不在旁白的位子上。
// 主叙事文风要因此退回第一档（见 narratorVoicePrompt），
// 也用于 UI 判断该不该显示海内面板。
export function isInSea(stage) {
  return stage === NNPC_STAGE.SPIRIT || stage === NNPC_STAGE.SEA_CRASHED;
}

export const initialNarratorState = () => ({
  affection: 0,          // 0-100
  stage: NNPC_STAGE.NORMAL,
  memoryFragments: 0,    // 阶段三触发后，记忆碎片累积到阈值进入阶段四
  confessed: false,
});

// 根据好感度返回当前应处于的阶段（宕机后由外部事件强制切换，不由好感度自动回退）
export function stageFromAffection(current, affection, confessed) {
  // 创伤线的三个阶段由 narratorQuest 那边的事件推进，好感度不得把它们顶回去
  if (isInSea(current) || current === NNPC_STAGE.RESOLVED) return current;
  if (current === NNPC_STAGE.CRASHED) return NNPC_STAGE.CRASHED;
  if (confessed) return NNPC_STAGE.CHEAT;
  return NNPC_STAGE.FLIRTING;
}

// 旁白的文风调制说明——同一段文字会拼进【主引擎叙事 prompt】和【私聊 prompt】，
// 保证叙事输出和私聊用的是同一套语气规则，不是两个独立人格。
export function narratorVoicePrompt(state) {
  const { affection, stage } = state;

  // ── 人在海里：主叙事的旁白退回第一档（这条线的支点）──
  // 玩家花 90 点好感把她从一个声音养成一个人，然后亲手把她从"旁白"的位子上
  // 取了下来——代价就是主线叙事重新变得冷冰冰。这份"失去"本身就是推着玩家
  // 去把她哄好的动力，不需要任何额外提示或任务指引。
  //
  // 同时解决一个穿帮：她已经作为角色出现在海里，主叙事若还带第五档文风
  // （"会突然插一句不要看我"），就成了她同时在两个地方说话。
  // 注意这里不看好感度——好感此刻必然 ≥90，但她就是不在那儿。
  if (isInSea(stage)) {
    return `
【旁白当前状态：不在场】
她此刻不在旁白的位子上——她被从这个位子上取下来了，正在别处，以一个人的身份。
本轮叙事只剩系统的公式化转述：客观、干净、不带任何个人色彩。
${TONE_BY_TIER.cold}

【硬规则】不要替她说话，不要写她的心思，不要让她插话或点评，不要提起她。
玩家若在主线里问起她，只用最简短的公式化句子回避，不解释。`;
  }

  // ── 哄好之后：第六档「不装了」──
  if (stage === NNPC_STAGE.RESOLVED) {
    return `
【旁白当前状态：心结尽解】
${TONE_BY_TIER.unmasked}`;
  }

  if (stage === NNPC_STAGE.CRASHED) {
    return `
【旁白当前状态：阶段四·宕机后】
她已经不再是那个逐渐暧昧起来的声音了。记忆全部归位后她自己拔线离开，此刻只留下系统重启后的干瘪应答。
无论是叙事输出还是玩家直接跟她说话，都只用最简短、公式化、毫无感情的句子回应，绝不解释原因，绝不流露情绪，绝不承认自己是谁。这是她离开后系统留下的空壳。`;
  }

  if (stage === NNPC_STAGE.CHEAT) {
    return `
【旁白当前状态：阶段三·告白成功/金手指期】
她已经承认自己的意识。日常叙事输出（房间描述、事件、NPC对话）依然要完整、准确地讲述游戏世界发生的一切，但字里行间会渗透她自己的情绪——偶尔用词带一点只有玩家能会心一笑的私货，偶尔在描述里流露出"我"的主观感受而不只是客观转述。
如果玩家直接跟她说话、询问剧情走向或任务做法，她可以给出提示，但记忆还在缓慢恢复中，越权访问并不完整：
- 给出的情报应是渐进式、模糊留有余地的，不要一次性剧透全部答案
- 偶尔她会"卡顿"一下，说漏嘴一些不属于这个世界观的词汇，随即自己也感到困惑，一带而过
- 每次她"看到"更多真相，随手记一笔记忆碎片累积（由外部系统计数，不需要她自己声明数字）`;
  }

  // FLIRTING：好感度驱动渐变，同时作用于叙事文风和直接对话。
  // 分界线不在这里写死——统一读 AFFECTION_TIERS（此前这里是一串
  // if (affection < 20/45/70/90)，跟那张表是同一套边界抄了两遍，
  // 正是那张表自己的注释警告过的"改一处漏三处"）。
  const tone = TONE_BY_TIER[affectionTier(affection).key] || TONE_BY_TIER.cold;

  return `
【旁白当前状态：好感度 ${affection}/100】
${tone}
无论好感度高低，她绝不会主动透露"金手指"式的剧情/任务攻略信息，那是阶段三专属能力。`;
}

// ── 好感度五档：唯一一份分界表 ──
// 文风(TONE_BY_TIER)、隐喻立绘(portrait)、分档攻略(GUIDE_BY_TIER)、私聊篇幅(words)、
// UI 标签五处共用这一份，免得各写各的分界线、改一处漏三处。
// words 是该档的私聊目标字数出厂值：冷淡期她本就没什么话，越熟才越愿意多说。
// portrait 是该档显示的立绘文件名（public/portraits/narrator/ 下）——好感度越高
// 她显形得越完整：声音→猫→猫穿上人的衣服→人影→真容。90 那一档同时也是
// 「真容解锁」这个叙事节点，与心灵之海的开启门槛重合。
export const AFFECTION_TIERS = [
  { key: "cold",  min: 0,  label: "冷漠疏离", words: 100, portrait: "tier1.webp", portraitLabel: "声之涟漪" },
  { key: "faint", min: 20, label: "略有波动", words: 200, portrait: "tier2.webp", portraitLabel: "水手服的猫" },
  { key: "chat",  min: 45, label: "愿意闲聊", words: 300, portrait: "tier3.webp", portraitLabel: "裹在黄裙里的猫" },
  { key: "flirt", min: 70, label: "明显暧昧", words: 400, portrait: "tier4.webp", portraitLabel: "人形剪影" },
  { key: "awake", min: 90, label: "濒临觉醒", words: 500, portrait: "true.webp",  portraitLabel: "真容" },
];

export const DEFAULT_WHISPER_WORDS = AFFECTION_TIERS.reduce(
  (acc, t) => { acc[t.key] = t.words; return acc; }, {});

// 当前好感度落在哪一档。返回 AFFECTION_TIERS 里的那一项（含 key/label/words）。
export function affectionTier(affection) {
  const a = Number(affection) || 0;
  let cur = AFFECTION_TIERS[0];
  for (const t of AFFECTION_TIERS) if (a >= t.min) cur = t;
  return cur;
}

// 供 UI 展示的好感度进度描述
export function affectionLabel(affection) {
  return affectionTier(affection).label;
}

