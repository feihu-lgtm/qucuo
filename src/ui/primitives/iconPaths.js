// 把一个图标序列化成 SVG 字符串（原型页、文档用；React 界面用 Icon 组件）。
export function iconSvg(name, size = 24) {
  const shapes = ICONS[name];
  if (!shapes) return "";
  const body = shapes.map(([tag, attrs]) => {
    const { fill, ...rest } = attrs;
    const fillAttr = fill ? ' fill="currentColor" stroke="none"' : "";
    return `<${tag} ${Object.entries(rest).map(([k, v]) => `${k}="${v}"`).join(" ")}${fillAttr}/>`;
  }).join("");
  return `<svg width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${body}</svg>`;
}
