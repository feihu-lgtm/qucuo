// ── 对话档专用的物品规范（talk scope 用它顶替整本「物件志」）──
// 对话轮确实可能发生物品往来（讨要、赠还、换物、当场付账），但为此挂一整本物件志
// 太重——那张表是给"凭空发物"的轮次准备的。对话轮里能易手的东西，来源其实很窄：
// 要么是玩家背包里已有的，要么是 [状态] 里那位 NPC〔身携:…〕列出来的。所以这里
// 只立规矩、不给全表，让模型照着 ctx 里已经写明的随身清单来，别自己现编。
//
// 双调用（narrativeOnly）下这条更要紧：主模型只写散文、由提取层照着散文记账，
// 散文里凭空掏出来的宝贝会被提取层当真、真的塞进玩家背包。所以两种模式都挂，
// 只是结尾那句"写不写 delta"仅对单调用（自己产 JSON）有意义。
export function buildTalkItemRule(narrativeOnly = false) {
  return "── 对话轮的物品规范 ──\n本轮是对话。若对白里确实发生物品往来（赠予、归还、易物、付账），只能取自两个来源：玩家背包里确实有的（见 [状态] 背包）；[状态] NPCs 〔身携:…〕列出之物。〔身无长物〕的人拿不出东西，不许现编其没有的宝贝，也不许把寻常物件说成稀世神兵。"
    + "正文只写真正当场易手的东西；嘴上提起、许诺日后再给、纯寒暄，不要写成已交到手上——后续记账完全照正文来，写虚了就会真的多出一件东西。";
}
