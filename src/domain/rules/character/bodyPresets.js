export function applyBodyPreset(currentProfile, preset, { includeIntimate = false } = {}) {
  const base = { ...emptyBodyProfile(), ...(currentProfile || {}) };
  if (!preset?.profile) return base;
  const fields = includeIntimate ? BODY_FIELDS : PUBLIC_FIELDS;
  for (const field of fields) {
    if (preset.profile[field.key] != null) base[field.key] = preset.profile[field.key];
  }
  return base;
}

export function appendBodyTag(currentValue, tag) {
  const cleanTag = String(tag || "").trim();
  if (!cleanTag) return String(currentValue || "");
  const cur = String(currentValue || "").trim();
  if (!cur) return cleanTag;
  if (cur.includes(cleanTag)) return cur;
  const sep = /[，。、；]$/.test(cur) ? "" : "，";
  return `${cur}${sep}${cleanTag}`;
}

