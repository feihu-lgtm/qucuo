// 查询某个 stage 有没有登记固定台本，按分支flag或默认返回具体文本；
// 都没有就返回 null（调用方据此判断这一回合要不要走"夺舍"路径，
// 还是照常走AI生成）。
export function getQuestScript(questId, stageId, hitFlags = []) {
  const stageScripts = QUEST_SCRIPTS[questId]?.[stageId];
  if (!stageScripts) return null;
  if (stageScripts.script_byFlag) {
    const matched = hitFlags.map(f => stageScripts.script_byFlag[f]).find(Boolean);
    if (matched) return matched;
    // 分支台本没能按 hitFlags 命中到具体版本时，不要瞎猜返回任意一支——
    // 宁可判定为"没有台本可用"，退回AI生成，也不能张冠李戴地展示错误分支的台词
    return null;
  }
  return stageScripts.script ?? null;
}
