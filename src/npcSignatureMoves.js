// 这个NPC的招式是否不可传授（野兽）。读专属表里的 unlearnable，或NPC自身的beast/unlearnable标记。
export function isUnlearnable(npc) {
  const sig = NPC_SIGNATURE_MOVES[npc?.name];
  return Boolean(npc?.unlearnable || npc?.beast || sig?.unlearnable);
}
